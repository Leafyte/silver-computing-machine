#!/usr/bin/env python3
"""
Quantum Circuit Walkthrough for DebugLeaf (Fleet Dispatch VQC)
============================================================

This script walks through our project's Variational Quantum Circuit (VQC)
step-by-step, showing how logistics data is encoded into quantum states,
processed through quantum gates, and measured to predict SLA delivery delay risk.
"""

from __future__ import annotations

import argparse
import math
import os
from pathlib import Path
from typing import Sequence

# Load .env credentials if available
try:
    from dotenv import load_dotenv
    load_dotenv(Path(__file__).resolve().parent.parent / ".env")
except ImportError:
    pass


def print_step(title: str, description: str):
    print("\n" + "=" * 70)
    print(f"  {title}")
    print("=" * 70)
    print(description.strip())
    print("-" * 70)


def build_and_simulate_vqc(
    features: Sequence[float] = (0.35, 0.25),
    theta: Sequence[float] = (0.31, -0.47),
    shots: int = 100,
    submit_cloud: bool = False,
):
    from qpiai_quantum import Circuit
    from qpiai_quantum.simulator import StatevectorSimulator

    x0, x1 = features[0], features[1]
    th0, th1 = theta[0], theta[1]

    print_step(
        "STEP 1: The Problem & Classical Features",
        f"""
We are evaluating a candidate delivery route.
Classical route features (normalized into [0, 1]):
  - x0 (Time Buffer Slack) = {x0:.2f}  (lower = tighter deadline)
  - x1 (Stop Density / Traffic) = {x1:.2f}  (higher = more congestion)

Trainable quantum weights (variational angles):
  - theta0 = {th0:.2f} radians
  - theta1 = {th1:.2f} radians
"""
    )

    print_step(
        "STEP 2: Allocating Qubits and Quantum Gates",
        """
We allocate a 2-qubit register:
  - Wire 0 (q[0]): Represents time-slack feature
  - Wire 1 (q[1]): Represents stop density feature

Gate Sequence:
  1. Feature Encoding:
     - Ry(pi * x0) on q[0]
     - Ry(pi * x1) on q[1]
  2. Quantum Entanglement:
     - CX (Controlled-NOT) from q[0] -> q[1]
  3. Variational Parameters:
     - Ry(theta0) on q[0]
     - Ry(theta1) on q[1]
  4. Second Entanglement:
     - CX (Controlled-NOT) from q[1] -> q[0]
"""
    )

    circuit = Circuit(2, name="DebugLeafDecisionVQC")
    
    # 1. Feature encoding
    circuit.ry(0, math.pi * x0)
    circuit.ry(1, math.pi * x1)
    
    # 2. Entanglement
    circuit.cx(0, 1)
    
    # 3. Trainable weights
    circuit.ry(0, th0)
    circuit.ry(1, th1)
    
    # 4. Feedback entanglement
    circuit.cx(1, 0)

    print("OpenQASM 2.0 Circuit Code generated by QpiAI Quantum:")
    print(circuit.to_qasm().strip())

    print_step(
        "STEP 3: Local Quantum Statevector Simulation",
        """
We execute the circuit on QpiAI Quantum's local StatevectorSimulator.
The simulator calculates the exact quantum state vector |psi>:
  |psi> = c00|00> + c01|01> + c10|10> + c11|11>
"""
    )

    sim = StatevectorSimulator()
    result = sim.run(circuit, shots=shots, seed=42)
    statevector = result.statevector

    for idx, amp in enumerate(statevector):
        bitstring = f"{idx:02b}"
        prob = abs(amp) ** 2
        bar = "#" * int(prob * 40)
        print(f"  |{bitstring}>: Amplitude = {amp.real:+.4f} {amp.imag:+.4f}j  --> Probability = {prob*100:5.2f}%  [{bar}]")

    print_step(
        "STEP 4: Quantum Measurement & SLA Risk Prediction",
        """
We measure the Pauli-Z expectation value on qubit 0 (<Z0>):
  <Z0> = P(q0 is 0) - P(q0 is 1)

Then map through a logistic sigmoid function:
  P(SLA breach) = 1 / (1 + exp(2 * <Z0>))
"""
    )

    z0 = sum((1.0 if i & 1 == 0 else -1.0) * abs(a) ** 2 for i, a in enumerate(statevector))
    risk_prob = 1.0 / (1.0 + math.exp(2.0 * z0))

    print(f"  Observable <Z0>          : {z0:+.4f}")
    print(f"  Predicted SLA Breach Risk: {risk_prob * 100:.2f}%")
    if risk_prob < 0.35:
        print("  -> Dispatch Recommendation: SAFE TO DISPATCH (Low Delay Exposure)")
    elif risk_prob < 0.65:
        print("  -> Dispatch Recommendation: MODERATE RISK (Buffer Recommended)")
    else:
        print("  -> Dispatch Recommendation: HIGH RISK OF BREACH (Re-route or classical fallback)")

    # STEP 5: Optional Cloud Submission
    if submit_cloud:
        print_step(
            "STEP 5: Submitting to QpiAI Quantum Cloud",
            "Submitting this exact circuit to QpiAI Cloud backend (QpiAI-QSV-Simulator)..."
        )
        qcloud_key = os.environ.get("QPIAI_QCLOUD_API_KEY")
        if not qcloud_key or qcloud_key.startswith("your_"):
            print("ERROR: QPIAI_QCLOUD_API_KEY is not set in .env. Skipping cloud submission.")
            return

        from qpiai_quantum import QpiAIQuantumAuth, JobManager
        QpiAIQuantumAuth.login(api_key=qcloud_key)
        
        # Add measurements for cloud execution
        cloud_circuit = Circuit(2, name="CloudDebugLeafVQC")
        cloud_circuit.ry(0, math.pi * x0)
        cloud_circuit.ry(1, math.pi * x1)
        cloud_circuit.cx(0, 1)
        cloud_circuit.ry(0, th0)
        cloud_circuit.ry(1, th1)
        cloud_circuit.cx(1, 0)
        cloud_circuit.measure_all()

        job_mgr = JobManager()
        sub = job_mgr.submit_circuit_job(
            circuit=cloud_circuit,
            experiment_name="DebugLeaf_Walkthrough",
            shots=shots,
            device_name="QpiAI-QSV-Simulator",
        )
        print(f"  Cloud Job Submitted Successfully!")
        print(f"  Job ID       : {sub.get('job_id')}")
        print(f"  Status       : {sub.get('status')}")
        print(f"  Experiment ID: {sub.get('experiment_id')}")
        print(f"  Device       : QpiAI-QSV-Simulator")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="DebugLeaf Quantum Circuit Walkthrough")
    parser.add_argument("--features", type=float, nargs=2, default=[0.35, 0.25], help="Two normalized features: x0 x1")
    parser.add_argument("--theta", type=float, nargs=2, default=[0.31, -0.47], help="Two trainable angles: th0 th1")
    parser.add_argument("--shots", type=int, default=100, help="Number of measurement shots")
    parser.add_argument("--cloud", action="store_true", help="Submit to QpiAI Cloud simulator")
    args = parser.parse_args()

    build_and_simulate_vqc(
        features=args.features,
        theta=args.theta,
        shots=args.shots,
        submit_cloud=args.cloud,
    )
